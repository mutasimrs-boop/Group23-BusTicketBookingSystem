CREATE TABLE app_users (
    user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR2(120) NOT NULL,
    email VARCHAR2(254) NOT NULL,
    phone VARCHAR2(25),
    password_hash VARCHAR2(255) NOT NULL,
    role VARCHAR2(12) DEFAULT 'CUSTOMER' NOT NULL CHECK (role IN ('ADMIN','CUSTOMER')),
    active CHAR(1) DEFAULT 'Y' NOT NULL CHECK (active IN ('Y','N')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_user_email UNIQUE (email)
);

CREATE TABLE cities (
    city_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_name VARCHAR2(100) NOT NULL,
    country VARCHAR2(80) DEFAULT 'Sudan' NOT NULL,
    active CHAR(1) DEFAULT 'Y' NOT NULL CHECK (active IN ('Y','N')),
    CONSTRAINT uq_city_name_country UNIQUE (city_name, country)
);

CREATE TABLE buses (
    bus_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bus_number VARCHAR2(20) NOT NULL UNIQUE,
    bus_name VARCHAR2(100),
    bus_type VARCHAR2(20) DEFAULT 'STANDARD' NOT NULL
        CHECK (bus_type IN ('STANDARD','VIP','SLEEPER','MINI')),
    total_seats NUMBER(3) NOT NULL CHECK (total_seats BETWEEN 1 AND 100),
    active CHAR(1) DEFAULT 'Y' NOT NULL CHECK (active IN ('Y','N')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- Physical seat map. Row/column allows the application to draw a real seat layout.
CREATE TABLE bus_seats (
    seat_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bus_id NUMBER NOT NULL REFERENCES buses(bus_id),
    seat_number VARCHAR2(8) NOT NULL,
    row_number NUMBER(3) NOT NULL CHECK (row_number > 0),
    column_number NUMBER(2) NOT NULL CHECK (column_number > 0),
    seat_type VARCHAR2(12) DEFAULT 'REGULAR' NOT NULL
        CHECK (seat_type IN ('REGULAR','WINDOW','AISLE','SLEEPER')),
    active CHAR(1) DEFAULT 'Y' NOT NULL CHECK (active IN ('Y','N')),
    CONSTRAINT uq_bus_seat_number UNIQUE (bus_id, seat_number),
    CONSTRAINT uq_bus_seat_position UNIQUE (bus_id, row_number, column_number)
);

CREATE TABLE routes (
    route_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origin_city_id NUMBER NOT NULL REFERENCES cities(city_id),
    destination_city_id NUMBER NOT NULL REFERENCES cities(city_id),
    distance_km NUMBER(7,1),
    estimated_minutes NUMBER(6),
    active CHAR(1) DEFAULT 'Y' NOT NULL CHECK (active IN ('Y','N')),
    CONSTRAINT ck_route_distinct_cities CHECK (origin_city_id <> destination_city_id),
    CONSTRAINT uq_route_pair UNIQUE (origin_city_id, destination_city_id)
);

CREATE TABLE schedules (
    schedule_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id NUMBER NOT NULL REFERENCES routes(route_id),
    bus_id NUMBER NOT NULL REFERENCES buses(bus_id),
    departure_at TIMESTAMP NOT NULL,
    arrival_at TIMESTAMP NOT NULL,
    base_fare NUMBER(10,2) NOT NULL CHECK (base_fare >= 0),
    status VARCHAR2(12) DEFAULT 'SCHEDULED' NOT NULL
        CHECK (status IN ('SCHEDULED','CANCELLED','COMPLETED')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT ck_schedule_times CHECK (arrival_at > departure_at)
);
CREATE INDEX ix_schedule_search ON schedules (route_id, departure_at, status);

CREATE TABLE bookings (
    booking_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_reference VARCHAR2(20) NOT NULL UNIQUE,
    user_id NUMBER REFERENCES app_users(user_id),
    schedule_id NUMBER NOT NULL REFERENCES schedules(schedule_id),
    passenger_name VARCHAR2(120) NOT NULL,
    passenger_phone VARCHAR2(25) NOT NULL,
    passenger_email VARCHAR2(254),
    booked_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    status VARCHAR2(12) DEFAULT 'CONFIRMED' NOT NULL
        CHECK (status IN ('CONFIRMED','CANCELLED','COMPLETED')),
    payment_status VARCHAR2(12) DEFAULT 'UNPAID' NOT NULL
        CHECK (payment_status IN ('UNPAID','PAID','REFUND_PENDING','REFUNDED')),
    total_amount NUMBER(10,2) NOT NULL CHECK (total_amount >= 0),
    cancelled_at TIMESTAMP,
    notes VARCHAR2(500)
);
CREATE INDEX ix_booking_phone ON bookings (passenger_phone, booked_at);

CREATE TABLE booking_seats (
    booking_seat_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id NUMBER NOT NULL REFERENCES bookings(booking_id),
    schedule_id NUMBER NOT NULL REFERENCES schedules(schedule_id),
    seat_id NUMBER NOT NULL REFERENCES bus_seats(seat_id),
    fare NUMBER(10,2) NOT NULL CHECK (fare >= 0),
    allocation_status VARCHAR2(10) DEFAULT 'BOOKED' NOT NULL
        CHECK (allocation_status IN ('BOOKED','CANCELLED'))
);
-- Prevent double-booking while allowing a seat to be rebooked after cancellation.
CREATE UNIQUE INDEX uq_active_schedule_seat ON booking_seats (
    CASE WHEN allocation_status = 'BOOKED' THEN schedule_id END,
    CASE WHEN allocation_status = 'BOOKED' THEN seat_id END
);

